function ajratJuftToq(arr) {
    let juft = arr.filter(function(son) {
        return son % 2 === 0;
    });
    let toq = arr.filter(function(son) {
        return son % 2 !== 0;
    });
    return [juft, toq];
}
console.log(ajratJuftToq([1, 2, 3, 4, 5, 6])); // [[2, 4, 6], [1, 3, 5]]    

